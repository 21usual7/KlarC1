// Registers every module in src/content/modules/: writes modules/index.ts (modules) and modules/icons.ts (Lucide icons).
// A module lives in `<module-id>.ts` (export const module) with its icons in `<module-id>.icons.ts` (export const icons).
// Run after adding or renaming a module file: node scripts/gen-content-index.mjs
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/content/modules/', import.meta.url);
const files = readdirSync(dir).filter(f => f.endsWith('.ts') && f !== 'index.ts' && f !== 'icons.ts').sort();
const modules = files.filter(f => !f.endsWith('.icons.ts'));
const icons = files.filter(f => f.endsWith('.icons.ts'));
const header = '// Generated by scripts/gen-content-index.mjs. Do not edit by hand.\n';

writeFileSync(new URL('index.ts', dir), header + "import type { Module } from '../types.ts';\n"
  + modules.map((f, i) => `import { module as m${i} } from './${f}';\n`).join('')
  + `\nexport const generatedModules: Module[] = [${modules.map((_, i) => `m${i}`).join(', ')}];\n`);
writeFileSync(new URL('icons.ts', dir), header
  + icons.map((f, i) => `import { icons as i${i} } from './${f}';\n`).join('')
  + `\nexport const generatedIcons = { ${icons.map((_, i) => `...i${i}`).join(', ')} };\n`);
console.log(`registered ${modules.length} modules, ${icons.length} icon files`);
